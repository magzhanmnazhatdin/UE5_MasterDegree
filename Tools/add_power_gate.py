import unreal as u
u.EditorLoadingAndSavingUtils.load_map('/Game/Midterm/Maps/Lvl_SignalVault')
s=u.get_editor_subsystem(u.EditorActorSubsystem)
aa={a.get_actor_label():a for a in s.get_all_level_actors()}
if 'PowerGate' in aa: raise RuntimeError('Power gate already installed')
cube=u.load_asset('/Engine/BasicShapes/Cube')
gate=s.spawn_actor_from_class(u.load_class(None,'/Game/ThirdPerson/Blueprints/BP_Door.BP_Door_C'),u.Vector(1900,0,500),u.Rotator(yaw=90))
gate.set_actor_label('PowerGate')
c=gate.get_editor_property('DoorMesh')
c.set_static_mesh(cube)
c.set_editor_property('relative_location',u.Vector(0,0,220))
c.set_editor_property('relative_scale3d',u.Vector(9.3,0.45,4.4))
c.set_material(0,u.load_asset('/Game/Midterm/Materials/M_Danger'))
t=gate.get_editor_property('ProximityTrigger')
t.set_editor_property('relative_location',u.Vector(0,0,120))
t.set_box_extent(u.Vector(470,200,150))
gate.set_editor_property('DoorOpenOffset',u.Vector(0,0,500))
plate=s.spawn_actor_from_class(u.load_class(None,'/Game/ThirdPerson/Blueprints/BP_Button.BP_Button_C'),u.Vector(1000,-300,510))
plate.set_actor_label('ConsolePowerPad')
plate.set_editor_property('TargetDoor',gate)
plate.get_editor_property('Cube').set_material(0,u.load_asset('/Game/Midterm/Materials/M_Amber'))
u.get_editor_subsystem(u.LevelEditorSubsystem).save_current_level()
u.log_warning('POWER_GATE_INSTALLED')
